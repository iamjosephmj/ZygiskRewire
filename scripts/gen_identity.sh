#!/usr/bin/env bash
# scripts/gen_identity.sh — generate this build's random identity.
# Usage: scripts/gen_identity.sh [outdir]   (default: build)
set -euo pipefail
OUT="${1:-build}"
MOD_DIR="$(cd "$(dirname "$0")/.." && pwd)"
mkdir -p "$OUT"

H="$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')"

MOD_ID="syscfg-${H:0:8}"
DAEMON_BIN="${H:8:6}d"        # installed as ${DAEMON_BIN}32 / ${DAEMON_BIN}64
PTRACER_BIN="${H:14:6}p"      # installed as ${PTRACER_BIN}32 / ${PTRACER_BIN}64
LIB_NAME="lib${H:20:8}.so"
TMP_PATH="/data/adb/${MOD_ID}"
SOCK_MON="m${H:28:8}"         # was: init_monitor
CP_BASE="c${H:36:6}"          # sockets: ${CP_BASE}32.sock / ${CP_BASE}64.sock
STATE_NAME="s${H:42:6}.json"  # was: state.json
SEPOL_TYPE="t${H:48:8}"       # was: zygisk_file
TAG="w${H:56:8}"              # log tag prefix, replaces all "zygisk*" tags

HASH_INPUT="${MOD_ID}${DAEMON_BIN}${PTRACER_BIN}${LIB_NAME}${SOCK_MON}${CP_BASE}${SEPOL_TYPE}${TAG}"
ID_HASH="$(printf '%s' "$HASH_INPUT" | sha256sum | cut -c1-16)"

cat > "$OUT/identity.mk" <<EOF
# Generated by scripts/gen_identity.sh — DO NOT COMMIT, DO NOT EDIT.
ID_MOD_ID := ${MOD_ID}
ID_DAEMON_BIN := ${DAEMON_BIN}
ID_PTRACER_BIN := ${PTRACER_BIN}
ID_LIB_NAME := ${LIB_NAME}
ID_TMP_PATH := ${TMP_PATH}
ID_SOCK_MON := ${SOCK_MON}
ID_CP_BASE := ${CP_BASE}
ID_STATE_NAME := ${STATE_NAME}
ID_SEPOL_TYPE := ${SEPOL_TYPE}
ID_TAG := ${TAG}
ID_HASH := ${ID_HASH}
EOF

cat > "$MOD_DIR/module/identity.env" <<EOF
# Generated by scripts/gen_identity.sh — consumed by customize.sh at install.
export ID_MOD_ID='${MOD_ID}'
export ID_DAEMON_BIN='${DAEMON_BIN}'
export ID_PTRACER_BIN='${PTRACER_BIN}'
export ID_LIB_NAME='${LIB_NAME}'
export ID_TMP_PATH='${TMP_PATH}'
export ID_HASH='${ID_HASH}'
export ID_SEPOL_TYPE='${SEPOL_TYPE}'
export ID_TAG='${TAG}'
EOF

echo "identity written to $OUT/identity.mk and module/identity.env (id=${MOD_ID})"
